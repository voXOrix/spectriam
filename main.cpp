void drawMenu(); 

bool needRedraw = true;

const unsigned long DEBOUNCE_DELAY = 35;       // filtr drgań styków
const unsigned long HOLD_DELAY = 400;          // po ilu ms zaczyna auto-przewijanie
const unsigned long REPEAT_INTERVAL = 90;      // co ile ms przewija przy trzymaniu

const uint8_t buttonPins[] = {
  BUTTON_UP_PIN,
  BUTTON_DOWN_PIN,
  BUTTON_SELECT_PIN
};

bool lastReading[3] = {HIGH, HIGH, HIGH};
bool stableState[3] = {HIGH, HIGH, HIGH};

unsigned long lastDebounceTime[3] = {0, 0, 0};
unsigned long pressedTime[3] = {0, 0, 0};
unsigned long lastRepeatTime[3] = {0, 0, 0};

bool buttonAutoRepeat(uint8_t buttonIndex) {
  unsigned long now = millis();

  bool reading = digitalRead(buttonPins[buttonIndex]);

  if (reading != lastReading[buttonIndex]) {
    lastDebounceTime[buttonIndex] = now;
    lastReading[buttonIndex] = reading;
  }

  if ((now - lastDebounceTime[buttonIndex]) > DEBOUNCE_DELAY) {
    if (reading != stableState[buttonIndex]) {
      stableState[buttonIndex] = reading;

      // Moment pierwszego kliknięcia
      if (stableState[buttonIndex] == LOW) {
        pressedTime[buttonIndex] = now;
        lastRepeatTime[buttonIndex] = now;
        return true;   // jedno przejście od razuk
      }
    }

    // Jeśli przycisk jest cały czas trzymany
    if (stableState[buttonIndex] == LOW) {
      if ((now - pressedTime[buttonIndex]) >= HOLD_DELAY) {
        if ((now - lastRepeatTime[buttonIndex]) >= REPEAT_INTERVAL) {
          lastRepeatTime[buttonIndex] = now;
          return true; // kolejne przewinięcie przy trzymaniu
        }
      }
    }
  }

  return false;
}
void drawMenu() {
  int item_sel_previous = item_selected - 1;

  if (item_sel_previous < 0) {
    item_sel_previous = NUM_ITEMS - 1;
  }

  int item_sel_next = item_selected + 1;

  if (item_sel_next >= NUM_ITEMS) {
    item_sel_next = 0;
  }

  u8g2.clearBuffer();

  u8g2.drawBitmap(0, 22, 128 / 8, 21, epd_bitmap__selector);

  u8g2.setFont(u8g2_font_10x20_tf);
  u8g2.drawStr(26, 15, menu_item[item_sel_previous]);
  u8g2.drawBitmap(4, 2, 16 / 8, 16, bitmap_icons[item_sel_previous]);

  u8g2.setFont(u8g2_font_t0_22b_tf);
  u8g2.drawStr(26, 38, menu_item[item_selected]);
  u8g2.drawBitmap(4, 24, 16 / 8, 16, bitmap_icons[item_selected]);

  u8g2.setFont(u8g2_font_10x20_tf);
  u8g2.drawStr(26, 59, menu_item[item_sel_next]);
  u8g2.drawBitmap(4, 46, 16 / 8, 16, bitmap_icons[item_sel_next]);

  u8g2.drawBitmap(120, 0, 8 / 8, 64, epd_bitmap__scrollbar);

  u8g2.sendBuffer();
}

void setup() {

  pinMode(BUTTON_UP_PIN, INPUT_PULLUP);
  pinMode(BUTTON_DOWN_PIN, INPUT_PULLUP);
  pinMode(BUTTON_SELECT_PIN, INPUT_PULLUP);
  
  u8g2.begin();  
  u8g2.setFont(u8g2_font_6x13_tf);
  u8g2.setColorIndex(1);
}

void loop() {

  if (buttonAutoRepeat(0)) {
    item_selected--;

    if (item_selected < 0) {
      item_selected = NUM_ITEMS - 1;
    }

    needRedraw = true;
  }

  if (buttonAutoRepeat(1)) {
    item_selected++;

    if (item_selected >= NUM_ITEMS) {
      item_selected = 0;
    }

    needRedraw = true;
  }

  if (buttonAutoRepeat(2)) {
    // SELECT
    // tutaj możesz dodać akcję po kliknięciu
  }

  if (needRedraw) {
    drawMenu();
    needRedraw = false;
  }
}
